/// Sobre qué figuras actúa el swing.
enum SwingGrid {
  /// Corcheas: la segunda corchea de cada pulso se retrasa (jazz, blues,
  /// shuffle). Con swing completo suenan como tresillos.
  eighth,

  /// Semicorcheas: la segunda semicorchea de cada corchea se retrasa (funk,
  /// hip-hop, lofi).
  sixteenth,
}
